try { const saved = localStorage.getItem('relay.lang'); if (dictionaries[saved]) lang = saved; } catch {}
function t(key, vars = {}) {
  let value = dictionaries[lang][key] || dictionaries.es[key] || key;
  for (const [name, text] of Object.entries(vars)) value = value.replaceAll('{'+name+'}', String(text));
  return value;
}
function apply(root = document) {
  document.documentElement.lang = lang;
  root.querySelectorAll('[data-access-i18n]').forEach(node => { node.textContent = t(node.dataset.accessI18n); });
}
function set(next) {
  if (!dictionaries[next]) return;
  lang = next;
  try { localStorage.setItem('relay.lang', lang); } catch {}
  apply();
  window.dispatchEvent(new CustomEvent('tasks-language-change', {detail:lang}));
}
